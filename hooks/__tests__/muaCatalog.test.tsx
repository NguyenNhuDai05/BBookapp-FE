import React from 'react';
import { act, renderHook, waitFor } from '@testing-library/react-native';
import { AppState } from 'react-native';
import { QueryClient, QueryClientProvider } from '@tanstack/react-query';
import { useMuaStyles } from '../useMuaStyles';
import { muaStyleService } from '../../services/muaStyleService';
jest.mock('../../services/muaStyleService', () => ({ muaStyleService: { getCatalog: jest.fn() } }));
jest.mock('../../services/api', () => ({ getApiError: (error: any) => ({ status: error.status }) }));
it('uses a single cache, refreshes on opening/resume and unsubscribes cleanly', async () => {
  const row = { styleId: 7, name: 'Mới từ admin', isActive: true };
  jest.mocked(muaStyleService.getCatalog).mockResolvedValue({ styles: [row], source: 'catalog', version: 'v1' });
  let listener: ((state: string) => void) | undefined;
  const remove = jest.fn();
  const spy = jest.spyOn(AppState, 'addEventListener').mockImplementation((_, callback: any) => { listener = callback; return { remove }; });
  const client = new QueryClient({ defaultOptions: { queries: { gcTime: Infinity } } });
  const wrapper = ({ children }: React.PropsWithChildren) => <QueryClientProvider client={client}>{children}</QueryClientProvider>;
  const first = await renderHook(() => useMuaStyles(), { wrapper });
  await waitFor(() => expect(first.result.current.data).toEqual([row]));
  expect(first.result.current.catalogSource).toBe('catalog');
  expect(client.getQueryCache().getAll()).toHaveLength(1);
  await first.unmount(); expect(remove).toHaveBeenCalledTimes(1);
  jest.mocked(muaStyleService.getCatalog).mockResolvedValue({ styles: [], source: 'catalog', version: 'v2' });
  const second = await renderHook(() => useMuaStyles(), { wrapper });
  await waitFor(() => expect(second.result.current.data).toEqual([]));
  expect(muaStyleService.getCatalog).toHaveBeenCalledTimes(2);
  await act(async () => { listener?.('active'); });
  await waitFor(() => expect(muaStyleService.getCatalog).toHaveBeenCalledTimes(3));
  await second.unmount(); client.clear(); spy.mockRestore();
});
